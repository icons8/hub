#!/usr/bin/env python3
"""A fake `codex app-server` (JSON-RPC 2.0 as lines over stdio): the Codex CLI 0.162 protocol, without a model.

It repeats what the 2026-10-19 probe showed (codex-cli 0.162.1, gpt-6-luna): initialize -> result; thread/start
(its own thread id) and thread/resume (the conversation from disk); turn/start -> a reply with the turn id, then
turn/started, item userMessage (the input text, with the [hub:mN] marker), steps, agentMessage,
thread/tokenUsage/updated, turn/completed. turn/steer mid-turn is one more userMessage in the same turn. Commands in the
text: `/ls` — a commandExecution step `ls`; `/ask` — an item/tool/requestUserInput request and waiting for the answer;
`/ask_async` — a question with the request_user_input_async tool (like the real 0.162, pilot 2026-10-19: an
agentMessage with a questions field, phase final_answer, the turn goes on and ends, the answer comes as the next
message); `/many` — a turn of several messages (commentary, final_answer, final_answer); `/slow` — a longer turn (for
steer and interrupt); `/crash` — the process crashes mid-turn. thread/compact/start -> thread/compacted. Conversations
live in $CODEX_HOME/fake-threads/<id>.json; thread/resume also takes a real Codex thread file from $CODEX_HOME/sessions
(its user messages are the history). FAKE_ROTATE_AUTH — every turn rewrites $CODEX_HOME/auth.json, like a token
refresh. Other methods (sign-in, limits, hooks…) and notifications after initialize
are set by the test in the $FAKE_CODEX_REPLIES file; a method neither knows gets {"result": {}}. $FAKE_CODEX_CALLS — a
file where every request of the client goes as a line {"method", "params", "known"} (known — the fake or the replies
file answers it itself), so a test sees what the host sent. Like the real 0.162.1 (probe 2026-11-05 without a model): an
experimental method or a top-level experimental field (not null) without capabilities.experimentalApi in initialize is
refused with -32600 "<method>[.<field>] requires experimentalApi capability", before the replies file; thread/start is a
new conversation — no history and no tokens of the previous thread.

The parity tests do not edit this file: their behavior comes from a replies file of their
test or a wrapper of their own, tests/fakes/codex_<slice>.py (slice M brought it closer to the real one: the two points
above).
"""
