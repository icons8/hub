def experimental(method, params):
    """What of the request needs experimentalApi ("<method>" or "<method>.<field>"), or None."""
    if method in EXPERIMENTAL_METHODS:
        return method
    for field in EXPERIMENTAL_FIELDS.get(method, ()):
        if params.get(field) is not None:
            return f"{method}.{field}"
    return None


def _snake(event):
    return re.sub(r"(?<!^)([A-Z])", r"_\1", event).lower()


def hooks_list():
    """hooks/list from $CODEX_HOME/hooks.json, shaped like the real 0.162 (probe 2026-10-19): the key is
    "<file>:<event>:i:j", eventName in camelCase; the hash is our own (sha256 of the entry), trust is trusted_hash under
    [hooks.state."<key>"] in config.toml; the file by its real path (live 0.162.1: a CODEX_HOME through a link is
    listed as the link's target — macOS's TMPDIR /var → /private/var)."""
    path = os.path.join(os.path.realpath(HOME), "hooks.json")
    try:
        with open(path, encoding="utf-8") as f:
            groups = (json.load(f) or {}).get("hooks") or {}
    except (OSError, ValueError):
        return []
    try:
        with open(os.path.join(HOME, "config.toml"), encoding="utf-8") as f:
            config = f.read()
    except OSError:
        config = ""
    out = []
    for event, entries in groups.items():
        for i, group in enumerate(entries or []):
            for j, hook in enumerate(group.get("hooks") or []):
                key = f"{path}:{_snake(event)}:{i}:{j}"
                digest = "sha256:" + hashlib.sha256(json.dumps(hook, sort_keys=True).encode()).hexdigest()
                # the key as a TOML string, as the core writes it and Codex reads it ("\\" escaped: Windows paths)
                trusted = re.search(r'\[hooks\.state\.' + re.escape(json.dumps(key)) + r'\]\s*\ntrusted_hash\s*=\s*"'
                                    + re.escape(digest) + '"', config)
                out.append({"key": key, "eventName": event[:1].lower() + event[1:], "handlerType": hook.get("type"),
                            "command": hook.get("command"), "matcher": group.get("matcher"), "sourcePath": path,
                            "source": "user", "enabled": True, "isManaged": False, "currentHash": digest,
                            "trustStatus": "trusted" if trusted else "untrusted"})
    return out


def rollout_of(thread):
    """The real Codex's thread file $CODEX_HOME/sessions/YYYY/MM/DD/rollout-<time>-<thread>.jsonl, or None."""
    for root, _, files in os.walk(os.path.join(HOME, "sessions")):
        for name in files:
            if name.startswith("rollout-") and name.endswith(f"-{thread}.jsonl"):
                return os.path.join(root, name)
    return None


def rollout_history(path):
    """The user messages of a real thread file (response_item message, role user), in order."""
    out = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            d = json.loads(line)
            p = d.get("payload") or {}
            if d.get("type") == "response_item" and p.get("type") == "message" and p.get("role") == "user":
                out.append("\n".join(c.get("text", "") for c in p.get("content") or []))
    return out


def rotate_auth():
    path = os.path.join(HOME, "auth.json")
    try:
        with open(path, encoding="utf-8") as f:
            got = json.load(f)
    except (OSError, ValueError):
        return
    got["rotated"] = got.get("rotated", 0) + 1
    with open(path + ".tmp", "w", encoding="utf-8") as f:
        json.dump(got, f)
    os.replace(path + ".tmp", path)


class Fake:
    def __init__(self):
        dump = os.environ.get("FAKE_ARGV_DIR")
        if dump:   # tests check what the core started the process with: arguments and environment (a Claude sign-in leak)
            os.makedirs(dump, exist_ok=True)
            with open(os.path.join(dump, f"codex-{os.environ.get('HUB_SESSION')}-{time.time_ns()}.json"), "w") as f:
                json.dump({"argv": sys.argv[1:], "env": dict(os.environ), "cwd": os.getcwd()}, f)
        self.lock = threading.Lock()
        self.thread = None
        self.history = []
        self.turn = None          # id of the running turn
        self.steered = []         # mid-turn input (turn/steer) — the turn reads it between steps
        self.answers = {}         # server request id -> the client's answer
        self.next_id = 1000
        self.turn_s = float(os.environ.get("FAKE_TURN_S", "0.2"))
        self.total = [0, 0]       # the thread's accumulated tokens (in, out)
        self.experimental = False  # initialize asked for capabilities.experimentalApi
        # replies to methods the fake does not know itself, and notifications after initialize — from the test's file
        # ($FAKE_CODEX_REPLIES: {"method": result | {"result"|"error": …, "notes": [{"method", "params", "after_s"}]}
        #  | [such, one per call], "_notes": [{"method", "params"}]})
        path = os.environ.get("FAKE_CODEX_REPLIES")
        self.replies = {}
        if path:
            with open(path, encoding="utf-8") as f:
                self.replies = json.load(f)

    def out(self, obj):
        with self.lock:
            sys.stdout.write(json.dumps(obj, ensure_ascii=False) + "\n")
            sys.stdout.flush()

    def note(self, method, **params):
        self.out({"method": method, "params": params, "emittedAtMs": int(time.time() * 1000)})

    def save(self):
        os.makedirs(THREADS, exist_ok=True)
        with open(os.path.join(THREADS, self.thread + ".json"), "w") as f:
            json.dump(self.history, f, ensure_ascii=False)

    def thread_obj(self, params):
        return {"id": self.thread, "sessionId": self.thread, "cwd": params.get("cwd"), "model": params.get("model"),
                "preview": (self.history[0] if self.history else "")[:80], "ephemeral": False}

    KNOWN = ("initialize", "initialized", "thread/start", "thread/resume", "turn/start", "turn/steer", "hooks/list",
             "skills/extraRoots/set", "turn/interrupt", "thread/compact/start")

    def log(self, method, params):
        path = os.environ.get("FAKE_CODEX_CALLS")
        if path:
            with self.lock, open(path, "a", encoding="utf-8") as f:
                f.write(json.dumps({"method": method, "params": params,
                                    "known": method in self.replies or method in self.KNOWN}, ensure_ascii=False) + "\n")

    def handle(self, msg):
        method, rid, params = msg.get("method"), msg.get("id"), msg.get("params") or {}
        if method is None and rid is not None:   # the client's answer to our request (requestUserInput)
            self.answers[rid] = msg.get("result", msg.get("error"))
            return
        self.log(method, params)
        need = None if self.experimental or method == "initialize" else experimental(method, params)
        if need and rid is not None:
            self.out({"id": rid, "error": {"code": -32600, "message": f"{need} requires experimentalApi capability"}})
            return
        if method == "initialize":
            self.experimental = ((params.get("capabilities") or {}).get("experimentalApi")) is True
            self.out({"id": rid, "result": {"userAgent": "fake/0.162.1", "codexHome": HOME,
                                            "platformFamily": "unix", "platformOs": sys.platform}})
            for note in self.replies.get("_notes") or []:   # server notifications right after initialize
                self.note(note["method"], **(note.get("params") or {}))
        elif method in self.replies:   # the test's replies to any methods (sign-in, limits, hooks…): a result or an error
            # a list — one per call in order (the last one repeats); {"notes": [...]} next to a reply are
            # notifications right after it (sign-in -> login/completed, limit -> rateLimits/updated)
            got = self.replies[method]
            if isinstance(got, list):
                got = got.pop(0) if len(got) > 1 else got[0]
            notes = (got.get("notes") or []) if isinstance(got, dict) else []
            if isinstance(got, dict) and ("result" in got or "error" in got):
                self.out({"id": rid, **({"error": got["error"]} if "error" in got else {"result": got["result"]})})
            else:
                self.out({"id": rid, "result": got})
            for note in notes:
                time.sleep(float(note.get("after_s") or 0))
                self.note(note["method"], **(note.get("params") or {}))
        elif method == "initialized":
            pass
        elif method == "thread/start":
            self.thread = str(uuid.uuid4())
            self.history, self.total = [], [0, 0]   # a new conversation: nothing of the previous thread
            self.save()
            self.out({"id": rid, "result": {"thread": self.thread_obj(params), "model": params.get("model") or "gpt-x",
                                            "cwd": params.get("cwd"), "approvalPolicy": params.get("approvalPolicy"),
                                            "sandbox": {"type": "dangerFullAccess"}, "modelProvider": "openai",
                                            "approvalsReviewer": "user"}})
            self.note("thread/started", thread=self.thread_obj(params))
        elif method == "thread/resume":
            path = os.path.join(THREADS, str(params.get("threadId")) + ".json")
            if os.environ.get("FAKE_RESUME_ERROR"):   # a failure not about a missing conversation (network, sign-in)
                self.out({"id": rid, "error": {"code": -32603, "message": os.environ["FAKE_RESUME_ERROR"]}})
                return
            rollout = rollout_of(str(params.get("threadId")))
            if not os.path.exists(path) and not rollout:
                self.out({"id": rid, "error": {"code": -32600, "message": f"no rollout found for thread id {params.get('threadId')}"}})
                return
            if os.path.exists(path):
                with open(path) as f:
                    self.history = json.load(f)
            else:   # a thread file of the real Codex (a copy in $CODEX_HOME/sessions): the user messages are the history
                self.history = rollout_history(rollout)
            self.thread = params["threadId"]
            self.out({"id": rid, "result": {"thread": self.thread_obj(params), "model": params.get("model") or "gpt-x",
                                            "cwd": params.get("cwd"), "approvalPolicy": params.get("approvalPolicy"),
                                            "sandbox": {"type": "dangerFullAccess"}, "modelProvider": "openai",
                                            "approvalsReviewer": "user"}})
        elif method == "turn/start":
            if self.turn:
                self.out({"id": rid, "error": {"code": -32600, "message": "turn already in progress"}})
                return
            tid = str(uuid.uuid4())
            self.turn = tid
            self.out({"id": rid, "result": {"turn": {"id": tid, "status": "inProgress", "items": []}}})
            threading.Thread(target=self.run_turn, args=(tid, params.get("input") or []), daemon=True).start()
        elif method == "turn/steer":
            if not self.turn or params.get("expectedTurnId") != self.turn:
                self.out({"id": rid, "error": {"code": -32600, "message": "no active turn to steer"}})
                return
            self.steered.append(params.get("input") or [])
            self.out({"id": rid, "result": {"turnId": self.turn}})
        elif method == "hooks/list":
            self.out({"id": rid, "result": {"data": [{"cwd": c, "hooks": hooks_list(), "warnings": [], "errors": []}
                                                     for c in params.get("cwds") or [None]]}})
        elif method == "skills/extraRoots/set":
            self.roots = params.get("extraRoots") or []
            self.out({"id": rid, "result": {}})
        elif method == "turn/interrupt":
            self.interrupted = params.get("turnId")
            self.out({"id": rid, "result": {}})
        elif method == "thread/compact/start":
            # like the real 0.162 (stand 2026-10-19): compaction is its own turn without a userMessage, with a contextCompaction step
            self.out({"id": rid, "result": {}})
            tid = self.turn = str(uuid.uuid4())
            self.note("turn/started", threadId=self.thread, turn={"id": tid, "status": "inProgress", "items": []})
            self.item("started", {"type": "contextCompaction", "id": "cmp-" + tid})
            self.history = self.history[-1:]
            self.save()
            self.item("completed", {"type": "contextCompaction", "id": "cmp-" + tid})
            self.turn = None
            self.note("turn/completed", threadId=self.thread, turn={"id": tid, "status": "completed", "items": [],
                                                                    "durationMs": 5})
        elif rid is not None:   # a method neither the fake nor the test's replies know: an empty result
            self.out({"id": rid, "result": {}})

    def item(self, kind, item):
        self.note(f"item/{kind}", item=item, threadId=self.thread, turnId=self.turn)

    def user(self, inp):
        text = "\n".join(i.get("text", "") for i in inp if i.get("type") == "text")
        item = {"type": "userMessage", "id": str(uuid.uuid4()), "content": [{"type": "text", "text": text}]}
        self.item("started", item)
        self.item("completed", item)
        self.history.append(text)
        return text

    def run_turn(self, tid, inp):
        t0 = time.time()
        self.interrupted = None
        self.note("turn/started", threadId=self.thread, turn={"id": tid, "status": "inProgress", "items": []})
        texts = [self.user(inp)]
        steps = 3 if any("/slow" in t for t in texts) else 1
        status, error = "completed", None
        for _ in range(steps):
            time.sleep(self.turn_s)
            while self.steered:
                texts.append(self.user(self.steered.pop(0)))
            if self.interrupted == tid:
                status = "interrupted"
                break
        text = texts[0]
        if "/crash" in text:
            os._exit(3)
        if "/ls" in text and status == "completed":
            cid = "exec-" + str(uuid.uuid4())
            cmd = {"type": "commandExecution", "id": cid, "command": "/bin/bash -lc ls", "cwd": os.getcwd(),
                   "status": "inProgress", "aggregatedOutput": None, "exitCode": None}
            self.item("started", cmd)
            self.item("completed", {**cmd, "status": "completed", "aggregatedOutput": "\n".join(sorted(os.listdir("."))) + "\n",
                                    "exitCode": 0, "durationMs": 1})
        if re.search(r"/ask\b", text) and status == "completed":
            qid = self.next_id
            self.next_id += 1
            self.out({"id": qid, "method": "item/tool/requestUserInput", "params": {
                "threadId": self.thread, "turnId": tid, "itemId": "call-ask", "isBlocking": True,
                "questions": [{"id": "color", "header": "Color", "question": "Which color?",
                               "options": [{"label": "blue", "description": ""}, {"label": "red", "description": ""}]}]}})
            while qid not in self.answers:
                time.sleep(0.02)
            got = ((self.answers[qid] or {}).get("answers") or {}).get("color", {}).get("answers") or []
            texts.append("answer: " + ", ".join(got))
        finals = []
        if "/ask_async" in text and status == "completed":
            ask = {"type": "agentMessage", "id": "call_" + uuid.uuid4().hex[:8], "phase": "final_answer",
                   "delivery": "async", "text": "Which color?\n- blue\n- red",
                   "questions": [{"title": "Which color?", "options": ["blue", "red"]}]}
            self.item("started", {**ask, "text": ""})
            self.item("completed", ask)
            time.sleep(self.turn_s)   # the turn goes on: the core's insert (a refusal of the question) gets into it
            later = [self.user(self.steered.pop(0)) for _ in list(self.steered)]
            finals.append({"type": "agentMessage", "id": "msg-" + str(uuid.uuid4()), "phase": "final_answer",
                           "text": "Waiting for your decision." + "".join(f" ok: {t}" for t in later)})
        elif "/many" in text and status == "completed":
            for phase, t in (("commentary", "Looking at the code."), ("final_answer", "Done: a fix in the file."),
                             ("final_answer", "Question: roll out to prod now or tomorrow?")):
                finals.append({"type": "agentMessage", "id": "msg-" + str(uuid.uuid4()), "phase": phase, "text": t})
        for msg in finals:
            self.item("started", {**msg, "text": ""})
            self.item("completed", msg)
        if finals:
            items = finals
        elif status == "completed":
            if re.search(r"/ask\b", text):
                reply = texts[-1]
            elif len(texts) > 1:
                reply = "ok: " + " + ".join(texts)
            else:
                reply = f"ok: {text}" + (f" (remembers {len(self.history) - 1})" if len(self.history) > 1 else "")
            msg = {"type": "agentMessage", "id": "msg-" + str(uuid.uuid4()), "text": reply, "phase": "final_answer"}
            self.item("started", {**msg, "text": ""})
            self.note("item/agentMessage/delta", threadId=self.thread, turnId=tid, itemId=msg["id"], delta=reply)
            self.item("completed", msg)
            items = [msg]
        else:
            items = []
        # like the real one (probe 2026-10-19): an update per model call — last of that call, total accumulated
        for inp, out in ((100, 20), (110, 5)):
            self.total = [self.total[0] + inp, self.total[1] + out]
            self.note("thread/tokenUsage/updated", threadId=self.thread, turnId=tid, tokenUsage={
                "total": {"totalTokens": sum(self.total), "inputTokens": self.total[0], "cachedInputTokens": 0,
                          "outputTokens": self.total[1], "reasoningOutputTokens": 0},
                "last": {"totalTokens": inp + out, "inputTokens": inp, "cachedInputTokens": 80, "outputTokens": out,
                         "reasoningOutputTokens": 0}, "modelContextWindow": 258400})
        self.save()
        if os.environ.get("FAKE_ROTATE_AUTH"):   # like the real one refreshing its token: a new auth.json in CODEX_HOME
            rotate_auth()
        self.turn = None
        self.note("turn/completed", threadId=self.thread, turn={
            "id": tid, "status": status, "items": items, "error": error,
            "startedAt": int(t0), "completedAt": int(time.time()), "durationMs": int((time.time() - t0) * 1000)})


def main():
    fake = Fake()
    for line in sys.stdin:
        try:
            msg = json.loads(line)
        except ValueError:
            continue
        fake.handle(msg)


if __name__ == "__main__":
    main()
